import pandas as pd

df = pd.read_csv("customer_history (1).csv")

df.head()

df.info()

df.describe()

df.describe(include="object")

df.describe(include="all")

df.isnull().sum()

df.duplicated().sum()

df["Review Rating"].describe()

df["Review Rating"] = df.groupby("Category")["Review Rating"].transform(
    lambda x: x.fillna(x.median())
)

df["Review Rating"].isnull().sum()

df.dtypes

df["Age"].describe()

df["Purchase Amount (USD)"].describe()

df["Review Rating"].describe()

#checking unique value in columns
for col in df.select_dtypes(include="object").columns:
    print("\n", col)
    print(df[col].unique())

#Categorical Data Validation
for col in df.select_dtypes(include="object").columns:
    print(f"\n{col}:")
    print(df[col].value_counts())

#Exploratory Data Analysis (EDA)
df["Gender"].value_counts()

#gender percentage
gender_pct = df["Gender"].value_counts(normalize=True) * 100
gender_pct

import matplotlib.pyplot as plt

df["Gender"].value_counts().plot(kind="bar")

plt.title("Customer Distribution by Gender")
plt.xlabel("Gender")
plt.ylabel("Number of Customers")
plt.xticks(rotation=0)
plt.show()

#category sales
category_sales = df.groupby("Category")["Purchase Amount (USD)"].sum().sort_values(ascending=False)

category_sales

category_sales.plot(kind="bar")

plt.title("Total Sales by Category")
plt.xlabel("Category")
plt.ylabel("Total Sales (USD)")
plt.xticks(rotation=0)
plt.show()

product_sales = df.groupby("Item Purchased")["Purchase Amount (USD)"].sum().sort_values(ascending=False)

product_sales

#Subscription Status Analysis
product_sales.head(10).sort_values().plot(kind="barh")

plt.title("Top 10 Products by Sales")
plt.xlabel("Total Sales (USD)")
plt.ylabel("Product")
plt.show()

subscription_sales = (
    df.groupby("Subscription Status")["Purchase Amount (USD)"]
    .agg(["count", "sum", "mean"])
)

subscription_sales

df.to_csv("customer_history_cleaned.csv", index=False)

